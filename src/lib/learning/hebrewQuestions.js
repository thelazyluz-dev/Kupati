const BANKS = [null, GRADE1, GRADE2, GRADE3, GRADE4, GRADE5, GRADE6]

function shuffleArr(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

export function getHebrewQuestions(grade, count = 5) {
  const bank = BANKS[Math.min(6, Math.max(1, grade))] || GRADE1
  const shuffled = shuffleArr(bank)
  return shuffled.slice(0, count).map(({ q, opts, a }) => ({
    question: q,
    options: opts,
    correctIndex: a,
  }))
}
